"""Run every deterministic fictional evaluation of the v2 stack into a NEW directory.

What: one command that reruns the fictional-only evaluations of Completion
Steps 10-17 and 20-21 with offline flags, writing every output under one new
output root (default ``data/eval-fictional/run-<UTC timestamp>``), plus a
``manifest.json`` with each command, exit code, wall time and the SHA-256 of
every file produced.

Why: Step 29 asks that published numbers be regenerated by commands rather
than hand-copied. Committed configs point at historical output folders, so the
training -> calibration -> policy chain runs from copies whose output paths are
rewritten into the new root; the committed configs and earlier outputs are
never touched.

Scope and limits: fictional/authored/generated data only, no network, no model
download, no API key. ``--skip-torch`` leaves out the training pilot chain when
the ``embeddings`` extra (torch) is not installed. Timing fields, UUIDs, timestamps and environment metadata can differ
between runs. Compare deterministic result fields separately; the manifest
records checksums but does not prove byte-for-byte reproducibility.
These are software-mechanics results, not matching-quality, calibration or
reviewer-benefit claims.

Usage::

    python -B scripts/eval_fictional.py [--output-root NEW_DIR] [--skip-torch]
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_PARENT = Path("data") / "eval-fictional"
OFFLINE_ENV = {
    "PYTHONDONTWRITEBYTECODE": "1",
    "PYTHONUTF8": "1",
    "HF_HUB_OFFLINE": "1",
    "TRANSFORMERS_OFFLINE": "1",
    "HF_HUB_DISABLE_TELEMETRY": "1",
    "LANGSMITH_TRACING": "false",
    "LANGCHAIN_TRACING_V2": "false",
}


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def _write_json(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x", encoding="utf-8", newline="\n") as stream:
        json.dump(payload, stream, indent=2, sort_keys=True, ensure_ascii=False)
        stream.write("\n")


def _derived_configs(out: Path) -> dict[str, Path]:
    """Copies of the pilot/calibration/policy configs writing under ``out``."""
    folder = out / "configs"
    pilot = json.loads(
        (ROOT / "eval/configs/train-pilot-fictional.json").read_text(encoding="utf-8")
    )
    calibration = json.loads(
        (ROOT / "eval/configs/calibration-v2.json").read_text(encoding="utf-8")
    )
    policy = json.loads(
        (ROOT / "eval/configs/review-policy-v2.json").read_text(encoding="utf-8")
    )
    model_dir = out / "training" / "char-ngram-pilot"
    rows = out / "training" / "selected-records.json"
    pilot["output_dir"] = model_dir.as_posix()
    pilot["selected_records_path"] = rows.as_posix()
    calibration["rows_path"] = rows.as_posix()
    calibration["output_dir"] = (out / "calibration").as_posix()
    calibration["source_bundle"] = (model_dir / "artifact").as_posix()
    policy["rows_path"] = rows.as_posix()
    policy["calibration_path"] = (
        out / "calibration" / "calibrator-platt.json"
    ).as_posix()
    policy["output_dir"] = (out / "policy").as_posix()
    paths = {
        "pilot": folder / "train-pilot-fictional.json",
        "calibration": folder / "calibration-v2.json",
        "policy": folder / "review-policy-v2.json",
    }
    for key, payload in (
        ("pilot", pilot),
        ("calibration", calibration),
        ("policy", policy),
    ):
        _write_json(paths[key], payload)
    return paths


def _steps(out: Path, skip_torch: bool) -> list[tuple[str, list[str], Path | None]]:
    """(name, module arguments, stdout file or None) in execution order."""
    steps: list[tuple[str, list[str], Path | None]] = [
        (
            "preprocessing",
            [
                "watchlist.preprocessing",
                "evaluate",
                "--config",
                "config/preprocessing.json",
                "--partition",
                "development",
            ],
            out / "preprocessing.json",
        ),
        (
            "baselines",
            [
                "watchlist.evaluate_baselines",
                "--config",
                "eval/configs/baselines-v2.json",
                "--output-root",
                (out / "baselines").as_posix(),
            ],
            out / "baselines.log",
        ),
        (
            "hybrid",
            [
                "watchlist.hybrid_retrieval",
                "evaluate",
                "--config",
                "eval/configs/baselines-v2.json",
                "--output-root",
                (out / "hybrid").as_posix(),
                "--partition",
                "development",
            ],
            out / "hybrid.log",
        ),
        (
            "memory",
            [
                "watchlist.case_memory.evaluation",
                "--config",
                "eval/configs/memory.json",
                "--output",
                (out / "memory.json").as_posix(),
            ],
            out / "memory.log",
        ),
    ]
    if not skip_torch:
        configs = _derived_configs(out)
        steps += [
            (
                "training_pilot",
                [
                    "watchlist.training",
                    "pilot",
                    "--config",
                    configs["pilot"].as_posix(),
                ],
                out / "training-pilot.json",
            ),
            (
                "calibration",
                [
                    "watchlist.calibration",
                    "fit",
                    "--config",
                    configs["calibration"].as_posix(),
                ],
                out / "calibration.json",
            ),
            (
                "policy",
                [
                    "watchlist.evaluate_policy",
                    "select",
                    "--partition",
                    "threshold_selection",
                    "--config",
                    configs["policy"].as_posix(),
                ],
                out / "policy.json",
            ),
        ]
    return steps


def run(out: Path, *, skip_torch: bool) -> dict:
    """Run all steps from the repository root; stop at the first failure."""
    if out.exists() or out.is_symlink():
        raise SystemExit(f"output root already exists; choose a new one: {out}")
    out.mkdir(parents=True)
    env = {**os.environ, **OFFLINE_ENV}
    src = str(ROOT / "src")
    env["PYTHONPATH"] = os.pathsep.join(
        [src, *([env["PYTHONPATH"]] if env.get("PYTHONPATH") else [])]
    )
    records = []
    ok = True
    for name, arguments, stdout_path in _steps(out, skip_torch):
        command = [sys.executable, "-B", "-m", *arguments]
        started = time.monotonic()
        with stdout_path.open("x", encoding="utf-8", newline="\n") as stream:
            process = subprocess.run(
                command,
                cwd=ROOT,
                env=env,
                stdout=stream,
                stderr=subprocess.PIPE,
                text=True,
                encoding="utf-8",
                check=False,
            )
        elapsed = round(time.monotonic() - started, 3)
        records.append(
            {
                "step": name,
                "command": ["python", "-B", "-m", *arguments],
                "exit_code": process.returncode,
                "wall_seconds": elapsed,
                "stderr_tail": process.stderr[-2000:],
            }
        )
        print(f"{name}: exit {process.returncode} in {elapsed} s", file=sys.stderr)
        if process.returncode != 0:
            ok = False
            break
    files = {
        path.relative_to(out).as_posix(): _sha256(path)
        for path in sorted(out.rglob("*"))
        if path.is_file()
    }
    manifest = {
        "evidence": "fictional/authored/generated data only; software mechanics, "
        "not matching-quality, calibration or reviewer-benefit results",
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "python": sys.version.split()[0],
        "platform": sys.platform,
        "skip_torch": skip_torch,
        "ok": ok,
        "steps": records,
        "files_sha256": files,
    }
    _write_json(out / "manifest.json", manifest)
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--output-root", type=Path, metavar="NEW_DIR")
    parser.add_argument(
        "--skip-torch",
        action="store_true",
        help="skip the training pilot -> calibration -> policy chain",
    )
    args = parser.parse_args()
    out = args.output_root or DEFAULT_PARENT / datetime.now(timezone.utc).strftime(
        "run-%Y%m%dT%H%M%SZ"
    )
    if not out.is_absolute():
        out = ROOT / out
    manifest = run(out, skip_torch=args.skip_torch)
    print(json.dumps({"output_root": str(out), "ok": manifest["ok"]}, indent=2))
    return 0 if manifest["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
